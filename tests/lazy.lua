vim.opt.runtimepath:prepend(vim.fn.getcwd())
local tools = require("keymap_tools")
local api = vim.api
local function unloaded(...)
  for _, name in ipairs({ ... }) do
    assert(not package.loaded[name], name .. " loaded before it was needed")
  end
end
tools.hide()
tools.register("early", { hints = { { keys = "qxy", desc = "Early metadata" } } })
unloaded("keymap_tools.config", "keymap_tools.context", "keymap_tools.query", "keymap_tools.hints", "keymap_tools.view")
assert(vim.v.vim_did_enter == 0, "this check must run before VimEnter")
tools.setup({ defer = true, hints = { delay = 10 } })
unloaded("keymap_tools.hints", "keymap_tools.view", "keymap_tools.picker", "selection_tools")
assert(#tools.list({ mode = "n", prefix = "qx" }) == 1)
unloaded("keymap_tools.hints", "keymap_tools.view")
tools.setup({ defer = true, hints = { delay = 30, triggers = { { prefix = "qx", modes = { "n" } } } } })
local startup = api.nvim_get_autocmds({ event = "VimEnter" })
assert(#startup == 1, "repeated setup must replace the pending initializer")
api.nvim_exec_autocmds("VimEnter", {})
assert(vim.fn.maparg("qx", "n", false, true).desc == "keymap-tools prefix hint")
assert(require("keymap_tools.config").get().hints.delay == 30)
unloaded("keymap_tools.view", "keymap_tools.picker", "selection_tools")
api.nvim_exec_autocmds("ColorScheme", {})
unloaded("keymap_tools.view")
tools.setup({ defer = true, hints = { enabled = false } })
assert(vim.fn.maparg("qx", "n") == "", "reconfiguration of an active engine must remain synchronous")
unloaded("keymap_tools.view")
assert(not pcall(tools.setup, { defer = "yes" }))
io.stdout:write("PASS metadata-only imports, deferred/replaced initialization, pre-input triggers and lazy rendering\n")
