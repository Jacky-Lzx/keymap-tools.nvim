vim.opt.runtimepath:prepend(vim.fn.getcwd())
local tools = require("keymap_tools")
tools.setup({ defer = true })
assert(not package.loaded["keymap_tools.hints"])
tools.refresh()
assert(package.loaded["keymap_tools.hints"], "explicit actions must activate deferred setup synchronously")
assert(#vim.api.nvim_get_autocmds({ event = "VimEnter" }) == 0, "explicit activation left a duplicate initializer")
assert(not package.loaded["keymap_tools.view"], "refresh must not initialize rendering")
assert(not package.loaded["keymap_tools.picker"] and not package.loaded["selection_tools"])
io.stdout:write("PASS explicit refresh activates pending setup without loading rendering or picker dependencies\n")
